class AcademyStore {
  private courses: AcademyCourse[] = ACADEMY_COURSES;
  private listeners: Set<() => void> = new Set();

  constructor() {
    this.load();
  }

  public subscribe(listener: () => void) {
    this.listeners.add(listener);
    return () => {
      this.listeners.delete(listener);
    };
  }

  private notify() {
    this.listeners.forEach((l) => l());
  }

  private load() {
    try {
      const saved = localStorage.getItem('forgemuscle_academy_courses');
      if (saved) {
        this.courses = JSON.parse(saved);
      }
    } catch {
      this.courses = ACADEMY_COURSES;
    }
  }

  private save() {
    try {
      localStorage.setItem('forgemuscle_academy_courses', JSON.stringify(this.courses));
    } catch {
      // ignore
    }
    this.notify();
  }

  public getCourses(): AcademyCourse[] {
    return this.courses;
  }

  public completeLesson(courseId: string, lessonId: string): number {
    const course = this.courses.find((c) => c.id === courseId);
    if (!course) return 0;

    const lesson = course.lessons.find((l) => l.id === lessonId);
    if (!lesson || lesson.isCompleted) return 0;

    lesson.isCompleted = true;
    course.completedLessonsCount = course.lessons.filter((l) => l.isCompleted).length;
    this.save();
    sound.playLevelUp();
    arnoVoice.speak(`Урок «${lesson.title}» пройдено! Твої знання загартовуються.`);
    return lesson.xpReward;
  }
}

export const academyStore = new AcademyStore();
